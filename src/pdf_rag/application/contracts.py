"""Step 3 public service interfaces, unchanged."""
from typing import Protocol, Sequence
from pdf_rag.domain.models import DocumentChunk, IngestionReport, PdfUpload, SynthesizedAnswer, VectorIndex, RetrieverResult
from pdf_rag.application.config import ChunkingPolicy, GenerationPolicy, IndexBuildConfig, IngestionPolicy, RetrievalPolicy

class DocumentProcessor(Protocol):
    def process_uploads(self, uploads: Sequence[PdfUpload], *, ingestion: IngestionPolicy, chunking: ChunkingPolicy) -> IngestionReport: ...

class VectorStoreManager(Protocol):
    def build_index(self, chunks: Sequence[DocumentChunk], *, config: IndexBuildConfig) -> VectorIndex: ...
    def retrieve(self, index: VectorIndex, question: str, *, policy: RetrievalPolicy) -> RetrieverResult: ...
    def clear(self) -> None: ...

class RAGPipeline(Protocol):
    def answer(self, index: VectorIndex, question: str, *, retrieval: RetrievalPolicy, generation: GenerationPolicy) -> SynthesizedAnswer: ...

class StreamlitApp(Protocol):
    def run(self) -> None: ...
